def test_relay_link_upgrades_to_direct_and_swaps_underneath_without_losing_frames():
    async def scenario():
        hub = Hub()
        hub.signals_enabled = False
        a, b, managers, state, hub = peer_pair(
            hub=hub, direct_timeout=0.3, upgrade_interval=0.4, upgrade_max_interval=0.8, swap_grace=0.4)
        impolite = a if a.node_id > b.node_id else b
        other = b if impolite is a else a
        try:
            link = await asyncio.wait_for(managers[impolite.node_id].connect(other.node_id), 10)
            assert link.tier == "ws-relay"
            await until(lambda: managers[other.node_id].link(impolite.node_id))
            peer_link = managers[other.node_id].link(impolite.node_id)
            received = []
            peer_link.handler = lambda lk, ch, env: received.append(env.data["n"])
            mine = []
            link.handler = lambda lk, ch, env: mine.append(env.data["n"])
            await link.send_frame("rpc", "http.request", {"n": 0}, "r0")
            await until(lambda: received == [0])
            await asyncio.sleep(0.5)  # at least one upgrade attempt fails: signals are dropped
            assert link.tier == "ws-relay" and managers[impolite.node_id]._upgrades
            for manager in managers.values():
                manager._connect_timeout = 20.0  # real ICE/DTLS needs longer than the failing probe
            hub.signals_enabled = True  # the network "recovers": the next attempt succeeds
            sent = 1
            deadline = asyncio.get_running_loop().time() + 30
            while link.tier != "direct" or peer_link.tier != "direct":
                assert asyncio.get_running_loop().time() < deadline, (link.tier, peer_link.tier)
                await link.send_frame("rpc", "http.request", {"n": sent}, f"r{sent}")
                await peer_link.send_frame("rpc", "http.response", {"n": 1000 + sent}, f"s{sent}")
                sent += 1
                await asyncio.sleep(0.02)
            for extra in range(5):  # and keep going over the new transport
                await link.send_frame("rpc", "http.request", {"n": sent + extra}, "x")
            total = sent + 5
            await until(lambda: sorted(received) == list(range(total)))
            await until(lambda: len(mine) >= sent - 1)
            # same objects all along: callers never saw a new link, on_link fired once per side
            assert managers[impolite.node_id].link(other.node_id) is link
            assert managers[other.node_id].link(impolite.node_id) is peer_link
            assert len(state["links"][impolite.node_id]) == 1 and len(state["links"][other.node_id]) == 1
            assert state["closed"][impolite.node_id] == [] and state["closed"][other.node_id] == []
            # the relay session was retired after the grace period
            await until(lambda: all(i.tier == "direct" for i in link.underlying), 10)
            await until(lambda: not managers[impolite.node_id]._relay.sessions, 10)
            assert link.tier == "direct" and not managers[impolite.node_id]._upgrades
        finally:
            await _close_managers(managers)
    run(scenario())


def test_direct_link_survives_a_stray_relay_session_as_standby_and_fails_over():
    async def scenario():
        hub = Hub()
        a, b, managers, state, hub = peer_pair(hub=hub, direct_timeout=5.0)
        try:
            link = await asyncio.wait_for(managers[a.node_id].connect(b.node_id), 30)
            assert link.tier == "direct"
            await until(lambda: managers[b.node_id].link(a.node_id))
            other_side = managers[b.node_id].link(a.node_id)
            # the peer opens a relay session anyway (e.g. its direct view differed): kept as standby
            await managers[b.node_id]._relay.connect(a.node_id)
            await until(lambda: len(link.underlying) == 2 and len(other_side.underlying) == 2)
            assert link.tier == "direct" and other_side.tier == "direct"
            got = []
            other_side.handler = lambda lk, ch, env: got.append(env.type)
            # the direct transport dies: the link fails over to the relay without on_link_closed
            direct_inner = link.current
            await direct_inner.close()
            await until(lambda: link.tier == "ws-relay")
            assert not link.closed.is_set() and state["closed"][a.node_id] == []
            await link.send_frame("control", "ping", {})
            await until(lambda: "ping" in got)
        finally:
            await _close_managers(managers)
    run(scenario())
