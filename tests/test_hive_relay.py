def test_simultaneous_initiators_lower_node_id_keeps_its_attempt():
    async def scenario():
        a, b, managers, sessions, hub = relay_pair()
        low, high = sorted((a, b), key=lambda i: i.node_id)
        try:
            results = await asyncio.wait_for(asyncio.gather(
                managers[a.node_id].connect(b.node_id), managers[b.node_id].connect(a.node_id)), 5)
            assert results[0].sid == results[1].sid
            assert len(sessions[a.node_id]) == 1 and len(sessions[b.node_id]) == 1
            m1_senders = {(src, sid) for src, _to, sid, raw in hub.frames if raw[0] == 1}
            assert (low.node_id, results[0].sid) in m1_senders  # the surviving attempt is the lower id's
            # the loser's M1 was ignored by the winner; the session works both ways
            got = []
            results[1].handler = lambda link, ch, env: got.append(env)
            await results[0].send_frame("control", "ping", {})
            await until(lambda: got)
        finally:
            await _close_all(managers)
    run(scenario())


def test_closing_a_session_notifies_the_peer_and_forgets_it():
    async def scenario():
        a, b, managers, sessions, hub = relay_pair()
        try:
            session_a = await asyncio.wait_for(managers[a.node_id].connect(b.node_id), 5)
            await until(lambda: sessions[b.node_id])
            await session_a.close()
            await until(lambda: sessions[b.node_id][0].closed.is_set())
            assert managers[a.node_id].session_for(b.node_id) is None
            assert managers[b.node_id].session_for(a.node_id) is None
            # peer offline -> its relay sessions are closed, a later connect starts afresh
            again = await asyncio.wait_for(managers[a.node_id].connect(b.node_id), 5)
            await managers[a.node_id].close_peer(b.node_id)
            assert again.closed.is_set()
        finally:
            await _close_all(managers)
    run(scenario())


