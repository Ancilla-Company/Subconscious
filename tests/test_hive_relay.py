# --- sessions (records) ---------------------------------------------------------------


def make_pair(a_id="n_aaaa", b_id="n_bbbb"):
    """Two wired sessions; ``out_a``/``out_b`` capture the raw records each side sent."""
    k_ab, k_ba, aad = os.urandom(32), os.urandom(32), os.urandom(32)
    out_a, out_b = [], []
    holder = {}

    async def tx_a(record):
        out_a.append(record)
        if not holder.get("cut"):
            holder["b"].on_record(record)

    async def tx_b(record):
        out_b.append(record)
        if not holder.get("cut"):
            holder["a"].on_record(record)

    a = RelaySession(node_id=b_id, role="hive_peer", local_id=a_id, sid="1.s", send_key=k_ab,
                     receive_key=k_ba, aad=aad, transmit=tx_a)
    b = RelaySession(node_id=a_id, role="hive_peer", local_id=b_id, sid="1.s", send_key=k_ba,
                     receive_key=k_ab, aad=aad, transmit=tx_b)
    holder.update(a=a, b=b)
    got_a, got_b = [], []
    a.handler = lambda link, ch, env: got_a.append((ch, env))
    b.handler = lambda link, ch, env: got_b.append((ch, env))
    return a, b, out_a, out_b, got_a, got_b, holder, (k_ab, k_ba, aad)


