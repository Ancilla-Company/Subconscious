# --- cross-language vectors (generated by Dart) -----------------------------------


def _vectors():
    return json.loads(VECTORS.read_text(encoding="utf-8"))


def _x25519(seed_b64u):
    private = X25519PrivateKey.from_private_bytes(b64u_decode(seed_b64u))
    public = private.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return private, public


def test_vectors_identities_keys_transcript_signatures_and_messages_match_dart():
    v = _vectors()
    assert v["version"] == 1
    initiator = NodeIdentity.from_seed(b64u_decode(v["initiator"]["seed"]))
    responder = NodeIdentity.from_seed(b64u_decode(v["responder"]["seed"]))
    assert initiator.public_key_b64u == v["initiator"]["public_key"]
    assert initiator.node_id == v["initiator"]["node_id"]
    assert responder.public_key_b64u == v["responder"]["public_key"]
    assert responder.node_id == v["responder"]["node_id"]

    eph_i_private, eph_i = _x25519(v["eph_i_seed"])
    eph_r_private, eph_r = _x25519(v["eph_r_seed"])
    assert b64u_encode(eph_i) == v["eph_i"] and b64u_encode(eph_r) == v["eph_r"]
    nonce_i, nonce_r = b64u_decode(v["nonce_i"]), b64u_decode(v["nonce_r"])

    transcript = relay_transcript(
        v["sid"], initiator.node_id, responder.node_id, eph_i, nonce_i, eph_r, nonce_r
    )
    assert b64u_encode(transcript) == v["transcript"]
    assert b64u_encode(hashlib.sha256(transcript).digest()) == v["transcript_sha256"]

    sig_r = responder.sign(responder_signed_bytes(transcript))
    sig_i = initiator.sign(initiator_signed_bytes(transcript))
    assert sig_r == v["sig_r"] and sig_i == v["sig_i"]

    # the handshake classes with the vector's fixed seeds and nonces reproduce M1, M2, M3
    i = RelayInitiator(initiator, responder.node_id, responder.public_key, v["sid"],
                       ephemeral_seed=b64u_decode(v["eph_i_seed"]), nonce=nonce_i)
    r = RelayResponder(responder, initiator.node_id, initiator.public_key, v["sid"],
                       ephemeral_seed=b64u_decode(v["eph_r_seed"]), nonce=nonce_r)
    m1 = i.start()
    assert b64u_encode(m1) == v["m1"]
    m2 = r.receive_m1(m1)
    assert b64u_encode(m2) == v["m2"]
    m3, keys_i = i.receive_m2(m2)
    assert b64u_encode(m3) == v["m3"]
    keys_r = r.receive_m3(m3)

    shared = eph_i_private.exchange(X25519PublicKey.from_public_bytes(eph_r))
    assert shared == eph_r_private.exchange(X25519PublicKey.from_public_bytes(eph_i))
    assert b64u_encode(shared) == v["shared"]
    derived = derive_relay_keys(shared, transcript)
    assert b64u_encode(derived.initiator_to_responder) == v["k_i2r"]
    assert b64u_encode(derived.responder_to_initiator) == v["k_r2i"]
    assert b64u_encode(derived.aad) == v["transcript_sha256"]
    assert keys_i == keys_r == derived


def test_vectors_data_and_close_records_match_dart_and_decrypt():
    v = _vectors()
    keys = {"i2r": b64u_decode(v["k_i2r"]), "r2i": b64u_decode(v["k_r2i"])}
    aad = b64u_decode(v["transcript_sha256"])
    assert v["data"], "the vector file must carry data frames"
    for frame in v["data"]:
        key = keys[frame["direction"]]
        record = b64u_decode(frame["record"])
        plaintext = frame["plaintext"].encode("utf-8")
        assert record[0] == MSG_DATA
        assert int.from_bytes(record[1:9], "big") == frame["counter"]
        # recompute (encrypt) and compare, then decrypt the Dart bytes
        assert seal_record(key, frame["counter"], aad, plaintext) == record
        assert open_record(key, record, aad) == plaintext
        assert open_record(key, record, bytes(32)) is None  # another transcript fails
    close = v["close"]
    record = b64u_decode(close["record"])
    assert record[0] == MSG_CLOSE and len(record) == 1 + 8 + 16
    assert seal_record(keys[close["direction"]], close["counter"], aad, b"", MSG_CLOSE) == record
    assert open_record(keys[close["direction"]], record, aad) == b""


def test_vectors_feed_a_session_exactly_like_dart_peers_would():
    """Responder-side session consumes the Dart i2r data frame and the authenticated close."""
    v = _vectors()
    aad = b64u_decode(v["transcript_sha256"])
