def test_rate_limiter_paces_messages_and_bytes():
    async def scenario():
        now = [0.0]
        slept = []

        async def sleep(seconds):
            slept.append(seconds)
            now[0] += seconds

        limiter = RateLimiter(1000, 2.0, 2, clock=lambda: now[0], sleep=sleep)
        await limiter.acquire(100)
        await limiter.acquire(100)  # burst of two messages is free
        assert slept == []
        await limiter.acquire(100)  # third message waits for a message token (0.5 s at 2/s)
        assert slept and abs(sum(slept) - 0.5) < 0.01
        slept.clear()
        await limiter.acquire(900)  # byte bucket: 100 refilled in 0.5 s ... wait for the rest
        assert slept and sum(slept) >= 0.45
    run(scenario())


# --- hub: behaves like the server's relay/signal forwarding -------------------------------


class Hub:
    def __init__(self):
        self.relay = {}  # node_id -> handle_relay coroutine function
        self.signal = {}  # node_id -> handle_signal
        self.signals_enabled = True
        self.mutate = None  # (frame, kind_byte) -> frame | None
        self.frames = []  # (from, to, sid, raw bytes)
        self.account = None

    def wire(self, node_id):
        hub = self

        class Wire:
            async def send_relay(self, sid, to, payload):
                assert 0 < len(payload) <= SERVER_PAYLOAD_CAP, "the server would reject this payload"
                raw = b64u_decode(payload)
                assert len(raw) <= RAW_LIMIT
                hub.frames.append((node_id, to, sid, raw))
                frame = {"sid": sid, "from": node_id, "payload": payload}
                if hub.mutate is not None:
                    frame = hub.mutate(frame, raw)
                target = hub.relay.get(to)
                if frame is not None and target is not None:
                    asyncio.ensure_future(target(frame))

            async def send_signal(self, sid, to, kind, body, sig):
                if not hub.signals_enabled:
                    return
                target = hub.signal.get(to)
                if target is None:
                    return
                frame = {"sid": sid, "from": node_id, "kind": kind, "body": body}
                if sig is not None:
                    frame["sig"] = sig
                asyncio.ensure_future(target(frame))

        return Wire()


def relay_pair(*, kinds=("engine",), hub=None, **manager_options):
    """Two RelayManagers in one account, directory-verified, over a hub."""
    a, b = NodeIdentity.generate(), NodeIdentity.generate()
    entries = make_entries(a, (b, kinds[0]))
    hub = hub or Hub()
    sessions = {a.node_id: [], b.node_id: []}
    managers = {}
    for me in (a, b):
        managers[me.node_id] = RelayManager(
            me, directory_for(me, entries), hub.wire(me.node_id),
            on_session=lambda s, n=me.node_id: sessions[n].append(s),
            limiter=fast_limiter(), **manager_options,
        )
        hub.relay[me.node_id] = managers[me.node_id].handle_relay
    return a, b, managers, sessions, hub


async def _close_all(managers):
    for manager in managers.values():
        await manager.close()


def test_handshake_succeeds_and_sessions_carry_data_both_ways():
    async def scenario():
        a, b, managers, sessions, hub = relay_pair()
        try:
            session_a = await asyncio.wait_for(managers[a.node_id].connect(b.node_id), 5)
            await until(lambda: sessions[b.node_id])
            session_b = sessions[b.node_id][0]
            assert session_a.sid == session_b.sid and session_a.tier == "ws-relay"
            assert session_a.role == session_b.role == "hive_peer"
            assert [raw[0] for *_x, raw in hub.frames][:3] == [1, 2, 3]  # M1, M2, M3 in order
            got = []
            session_b.handler = lambda link, ch, env: got.append(env)
            await session_a.send_frame("control", "ping", {"n": 1}, "p1")
            await until(lambda: got)
            back = []
            session_a.handler = lambda link, ch, env: back.append(env)
            await session_b.send_frame("rpc", "http.response", {"status": 200}, "p1")
            await until(lambda: back)
            assert managers[a.node_id].session_for(b.node_id) is session_a
        finally:
            await _close_all(managers)
    run(scenario())


