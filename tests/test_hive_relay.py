def peer_pair(*, hub=None, ice=None, a_options=None, b_options=None, **common):
    a, b = NodeIdentity.generate(), NodeIdentity.generate()
    entries = make_entries(a, (b, "engine"))
    hub = hub or Hub()
    state = {"links": {a.node_id: [], b.node_id: []}, "closed": {a.node_id: [], b.node_id: []}}

    async def default_ice():
        return {"ice_servers": [], "ws_relay_enabled": True, "ttl": 300}

    managers = {}
    for me, options in ((a, a_options or {}), (b, b_options or {})):
        wire = hub.wire(me.node_id)
        manager = PeerManager(
            me, directory_for(me, entries), wire, ice or default_ice,
            on_link=lambda link, n=me.node_id: state["links"][n].append(link),
            on_link_closed=lambda node, n=me.node_id: state["closed"][n].append(node),
            relay_sender=wire, relay_limiter=fast_limiter(), **{**common, **options},
        )
        managers[me.node_id] = manager
        hub.relay[me.node_id] = manager.handle_relay
        hub.signal[me.node_id] = manager.handle_signal
    return a, b, managers, state, hub


async def _close_managers(managers):
    for manager in managers.values():
        await manager.close()


def test_direct_failure_falls_back_to_relay_with_tier_ws_relay():
    async def scenario():
        hub = Hub()
        hub.signals_enabled = False  # the direct attempt gets no answer
        a, b, managers, state, hub = peer_pair(hub=hub, direct_timeout=0.3)
        try:
            link = await asyncio.wait_for(managers[a.node_id].connect(b.node_id), 10)
            assert link.tier == "ws-relay" and managers[a.node_id].state_of(b.node_id) == "connected"
            await until(lambda: managers[b.node_id].link(a.node_id))
            assert managers[b.node_id].link(a.node_id).tier == "ws-relay"
            # on_link fired exactly once per side and the same object is returned from now on
            assert state["links"][a.node_id] == [link] and len(state["links"][b.node_id]) == 1
            assert managers[a.node_id].link(b.node_id) is link
            assert await managers[a.node_id].connect(b.node_id) is link
            got = []
            managers[b.node_id].link(a.node_id).handler = lambda lk, ch, env: got.append((ch, env.type))
            await link.send_frame("rpc", "http.request", {"method": "GET", "path": "/api/v1/x"}, "r1")
            await until(lambda: got)
            assert got == [("rpc", "http.request")]
            await link.close()
            await until(lambda: state["closed"][a.node_id] == [b.node_id])
            await until(lambda: state["closed"][b.node_id] == [a.node_id])
            assert managers[a.node_id].link(b.node_id) is None
        finally:
            await _close_managers(managers)
    run(scenario())


def test_relay_is_not_used_when_the_server_does_not_enable_it_or_the_config_disables_it():
    async def scenario():
        async def no_relay_ice():
            return {"ice_servers": [], "ws_relay_enabled": False}

        hub = Hub()
        hub.signals_enabled = False
        a, b, managers, _state, hub = peer_pair(hub=hub, ice=no_relay_ice, direct_timeout=0.2)
        try:
            with pytest.raises(ConnectionError):
                await asyncio.wait_for(managers[a.node_id].connect(b.node_id), 10)
            assert hub.frames == []  # nothing went through the relay
            assert managers[a.node_id].state_of(b.node_id) == "failed"
        finally:
            await _close_managers(managers)

        hub = Hub()
        hub.signals_enabled = False
        a, b, managers, _state, hub = peer_pair(hub=hub, direct_timeout=0.2, relay_enabled=False)
        try:
            assert not managers[a.node_id].relay_enabled
            with pytest.raises(ConnectionError):
                await asyncio.wait_for(managers[a.node_id].connect(b.node_id), 10)
            assert hub.frames == []
        finally:
            await _close_managers(managers)
    run(scenario())


