def test_inactive_unknown_and_revoked_nodes_are_not_answered():
    async def scenario():
        from hive_testkit import entry

        a, b, c = NodeIdentity.generate(), NodeIdentity.generate(), NodeIdentity.generate()
        entries = make_entries(a, (b, "engine"))
        entries.append(entry(c, kind="engine", approver=a, status="revoked"))
        hub = Hub()
        ma = RelayManager(a, directory_for(a, entries), hub.wire(a.node_id), limiter=fast_limiter())
        hub.relay[a.node_id] = ma.handle_relay
        try:
            for outsider in (c, NodeIdentity.generate()):  # revoked member / never heard of
                m1 = RelayInitiator(outsider, a.node_id, a.public_key, "1.sid").start()
                await ma.handle_relay({"sid": "1.sid", "from": outsider.node_id, "payload": b64u_encode(m1)})
            await asyncio.sleep(0.05)
            assert hub.frames == []
            with pytest.raises(RelayError):
                await ma.connect(c.node_id)  # and we do not dial them either
            with pytest.raises(RelayError):
                await ma.connect("n_" + "q" * 26)
        finally:
            await ma.close()
    run(scenario())


def test_malformed_relay_frames_are_dropped_silently():
    async def scenario():
        a, b, managers, sessions, hub = relay_pair()
        try:
            handle = managers[b.node_id].handle_relay
            for frame in (
                {}, {"from": a.node_id}, {"from": a.node_id, "sid": "s", "payload": 5},
                {"from": a.node_id, "sid": "", "payload": "AQ"}, {"from": a.node_id, "sid": "s", "payload": "!!"},
                {"from": a.node_id, "sid": "s" * 200, "payload": "AQ"},
                {"from": a.node_id, "sid": "s", "payload": b64u_encode(bytes([1]) + bytes(5))},
                {"from": a.node_id, "sid": "s", "payload": b64u_encode(bytes([2]) + bytes(112))},  # M2 without a handshake
                {"from": a.node_id, "sid": "s", "payload": b64u_encode(bytes([0x10]) + bytes(40))},
                {"from": b.node_id, "sid": "s", "payload": b64u_encode(bytes([1]) + bytes(48))},  # from ourselves
            ):
                await handle(frame)
            assert hub.frames == [] and managers[b.node_id].sessions == []
        finally:
            await _close_all(managers)
    run(scenario())


def test_one_attempt_per_peer_pair_and_sid():
    async def scenario():
        a, b, managers, sessions, hub = relay_pair()
        try:
            session = await asyncio.wait_for(managers[a.node_id].connect(b.node_id), 5)
            await until(lambda: sessions[b.node_id])
            m1 = next(raw for src, _to, _sid, raw in hub.frames if raw[0] == 1)
            sent = len(hub.frames)
            # the same M1 again (same sid), after the session exists: routed to the session, ignored
            await managers[b.node_id].handle_relay(
                {"sid": session.sid, "from": a.node_id, "payload": b64u_encode(m1)})
            await asyncio.sleep(0.05)
            assert len(hub.frames) == sent and len(sessions[b.node_id]) == 1
            # after the session is gone the sid is still remembered: no second handshake for it
            await session.close()
            await until(lambda: not managers[b.node_id].sessions)
            await managers[b.node_id].handle_relay(
                {"sid": session.sid, "from": a.node_id, "payload": b64u_encode(m1)})
            await asyncio.sleep(0.05)
            assert not any(raw[0] == 2 and sid == session.sid for _s, _t, sid, raw in hub.frames[sent:])
            # a pending responder per peer blocks a different sid until it completes or times out
            m1_other = RelayInitiator(a, b.node_id, b.public_key, "9.other").start()
            m1_third = RelayInitiator(a, b.node_id, b.public_key, "9.third").start()
            before = len(hub.frames)
            await managers[b.node_id].handle_relay({"sid": "9.other", "from": a.node_id, "payload": b64u_encode(m1_other)})
            await managers[b.node_id].handle_relay({"sid": "9.third", "from": a.node_id, "payload": b64u_encode(m1_third)})
            await asyncio.sleep(0.05)
            assert sum(1 for *_x, raw in hub.frames[before:] if raw[0] == 2) == 1
        finally:
            await _close_all(managers)
    run(scenario())


