// Cross-implementation test vectors for the socket relay (webrtc.md Appendix B).
//
// File: subconscious-dart/tests/vectors/relay_v1.json (override the path with
// the RELAY_VECTORS environment variable).
//
// All binary values are base64url without padding. Schema:
//   sid                      relay session id used in T
//   initiator / responder    {seed, public_key, node_id}: Ed25519 identity
//   eph_i_seed, eph_r_seed   32 byte X25519 private seeds (fixed, test only)
//   eph_i, eph_r             X25519 public keys derived from the seeds
//   nonce_i, nonce_r         16 byte handshake nonces
//   transcript               T = "sc-relay-v1\n" sid "\n" I "\n" R "\n"
//                            eph_i nonce_i eph_r nonce_r   (raw bytes)
//   transcript_sha256        SHA-256(T): HKDF salt and AEAD AAD
//   sig_r                    Ed25519(sk_R, "sc-relay-resp-v1\n" + T)
//   sig_i                    Ed25519(sk_I, "sc-relay-init-v1\n" + T)
//   m1, m2, m3               handshake messages (0x01|eph_i|nonce_i,
//                            0x02|eph_r|nonce_r|sig_r, 0x03|sig_i)
//   shared                   X25519(eph_i_priv, eph_r) (32 bytes)
//   k_i2r, k_r2i             HKDF-SHA256(shared, salt = SHA-256(T),
//                            info = "sc-relay-keys-v1", 64) split in halves
//   data[]                   {direction: "i2r"|"r2i", counter, plaintext
//                            (UTF-8 JSON text), record}: record is
//                            0x10 | counter(8, BE) | ciphertext | tag with
//                            nonce = 4 zero bytes | counter and AAD = SHA-256(T)
//   close                    {direction, counter, record}: 0x20 | counter |
//                            tag, i.e. an authenticated close over an empty
//                            plaintext (a bare 0x20 byte is ignored).
//
// The test recomputes every value from the fixed inputs. If the file is
// missing it is written; if it exists (e.g. regenerated by the Python engine
// with the same inputs) every present field must match.
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:core_business_logic/core_business_logic.dart';
import 'package:cryptography/cryptography.dart';
import 'package:test/test.dart';

List<int> _seq(int start, int length) =>
    List<int>.generate(length, (int i) => (start + i) & 0xff);

Future<Map<String, dynamic>> _compute() async {
  final NodeIdentity initiator = await NodeIdentity.fromSeed(_seq(0x01, 32));
  final NodeIdentity responder = await NodeIdentity.fromSeed(_seq(0x41, 32));
  const String sid = '1700000000.AAAAAAAAAAAA';
  final List<int> ephISeed = _seq(0x20, 32);
  final List<int> ephRSeed = _seq(0x60, 32);
  final List<int> nonceI = _seq(0xa0, 16);
  final List<int> nonceR = _seq(0xb0, 16);

  final SimpleKeyPair ephI = await X25519().newKeyPairFromSeed(ephISeed);
  final SimpleKeyPair ephR = await X25519().newKeyPairFromSeed(ephRSeed);
  final List<int> pubI = (await ephI.extractPublicKey()).bytes;
  final List<int> pubR = (await ephR.extractPublicKey()).bytes;

  final Uint8List transcript = relayTranscript(
    sid: sid,
    initiatorId: initiator.nodeId,
    responderId: responder.nodeId,
    ephI: pubI,
    nonceI: nonceI,
    ephR: pubR,
    nonceR: nonceR,
  );
  final Uint8List sigR = await responder.signBytes(relayResponderSignedBytes(transcript));
  final Uint8List sigI = await initiator.signBytes(relayInitiatorSignedBytes(transcript));
  final List<int> shared = await (await X25519().sharedSecretKey(
    keyPair: ephI,
    remotePublicKey: SimplePublicKey(pubR, type: KeyPairType.x25519),
  )).extractBytes();
  final RelayKeys keys = await deriveRelayKeys(shared, transcript);

  Future<Map<String, dynamic>> data(
    String direction,
    int counter,
    String plaintext,
  ) async => <String, dynamic>{
    'direction': direction,
    'counter': counter,
    'plaintext': plaintext,
    'record': b64uEncode(
      await relaySeal(
        key: direction == 'i2r' ? keys.initiatorToResponder : keys.responderToInitiator,
        counter: counter,
        aad: keys.aad,
        plaintext: utf8.encode(plaintext),
      ),
    ),
  };

  Map<String, dynamic> identityJson(NodeIdentity id, List<int> seed) =>
      <String, dynamic>{
        'seed': b64uEncode(seed),
        'public_key': id.publicKeyB64u,
        'node_id': id.nodeId,
      };

  return <String, dynamic>{
    'version': 1,
    'sid': sid,
    'initiator': identityJson(initiator, _seq(0x01, 32)),
    'responder': identityJson(responder, _seq(0x41, 32)),
    'eph_i_seed': b64uEncode(ephISeed),
    'eph_i': b64uEncode(pubI),
    'nonce_i': b64uEncode(nonceI),
    'eph_r_seed': b64uEncode(ephRSeed),
    'eph_r': b64uEncode(pubR),
    'nonce_r': b64uEncode(nonceR),
    'transcript': b64uEncode(transcript),
    'transcript_sha256': b64uEncode(keys.aad),
    'sig_r': b64uEncode(sigR),
    'sig_i': b64uEncode(sigI),
    'm1': b64uEncode(<int>[relayMsgM1, ...pubI, ...nonceI]),
    'm2': b64uEncode(<int>[relayMsgM2, ...pubR, ...nonceR, ...sigR]),
    'm3': b64uEncode(<int>[relayMsgM3, ...sigI]),
    'shared': b64uEncode(shared),
    'k_i2r': b64uEncode(keys.initiatorToResponder),
    'k_r2i': b64uEncode(keys.responderToInitiator),
    'data': <Map<String, dynamic>>[
      await data(
        'i2r',
        0,
        '{"ch":"rpc","env":{"v":1,"type":"http.request","id":"h-0","data":{"method":"GET","path":"/api/v1/models"}}}',
      ),
      await data(
        'r2i',
        5,
        '{"ch":"events","env":{"v":1,"type":"chat.delta","id":"t1","data":{"delta":"hello"}}}',
      ),
    ],
    'close': <String, dynamic>{
      'direction': 'i2r',
      'counter': 1,
      'record': b64uEncode(
        await relaySeal(
          key: keys.initiatorToResponder,
          counter: 1,
          aad: keys.aad,
          plaintext: const <int>[],
          type: relayMsgClose,
        ),
      ),
    },
  };
}

File _vectorFile() => File(
  Platform.environment['RELAY_VECTORS'] ?? '../../tests/vectors/relay_v1.json',
);

void main() {
  test('relay v1 vectors are reproducible and match the stored file', () async {
    final Map<String, dynamic> computed = await _compute();
    final File file = _vectorFile();
    if (!file.existsSync()) {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(
        '${const JsonEncoder.withIndent('  ').convert(computed)}\n',
      );
    }
    final Map<String, dynamic> stored =
        jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
    for (final MapEntry<String, dynamic> entry in computed.entries) {
      if (!stored.containsKey(entry.key)) continue;
      expect(
        jsonEncode(stored[entry.key]),
        jsonEncode(entry.value),
        reason: 'vector field ${entry.key}',
      );
    }
    expect(stored['k_i2r'], isNotNull);
  });

  test('the handshake classes reproduce the vector messages', () async {
    final Map<String, dynamic> v = await _compute();
    final NodeIdentity initiator = await NodeIdentity.fromSeed(_seq(0x01, 32));
    final NodeIdentity responder = await NodeIdentity.fromSeed(_seq(0x41, 32));
    final RelayInitiator i = RelayInitiator(
      identity: initiator,
      remoteNodeId: responder.nodeId,
      remotePublicKey: responder.publicKey,
      sid: v['sid'] as String,
      ephemeralSeed: _seq(0x20, 32),
      nonce: _seq(0xa0, 16),
    );
    final RelayResponder r = RelayResponder(
      identity: responder,
      remoteNodeId: initiator.nodeId,
      remotePublicKey: initiator.publicKey,
      sid: v['sid'] as String,
      ephemeralSeed: _seq(0x60, 32),
      nonce: _seq(0xb0, 16),
    );
    final Uint8List m1 = await i.start();
    expect(b64uEncode(m1), v['m1']);
    final Uint8List m2 = await r.receiveM1(m1);
    expect(b64uEncode(m2), v['m2']);
    final ({Uint8List m3, RelayKeys keys}) fin = await i.receiveM2(m2);
    expect(b64uEncode(fin.m3), v['m3']);
    final RelayKeys keys = await r.receiveM3(fin.m3);
    expect(b64uEncode(keys.initiatorToResponder), v['k_i2r']);
    expect(b64uEncode(fin.keys.responderToInitiator), v['k_r2i']);

    // The stored data frame decrypts with the derived key.
    final Map<String, dynamic> frame = (v['data'] as List<Object?>).first as Map<String, dynamic>;
    final Uint8List? clear = await relayOpen(
      key: keys.initiatorToResponder,
      record: b64uDecode(frame['record'] as String),
      aad: keys.aad,
    );
    expect(utf8.decode(clear!), frame['plaintext']);
    // A different AAD (another transcript) fails authentication.
    expect(
      await relayOpen(
        key: keys.initiatorToResponder,
        record: b64uDecode(frame['record'] as String),
        aad: List<int>.filled(32, 7),
      ),
      isNull,
    );
  });
}
